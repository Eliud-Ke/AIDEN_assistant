# Preserve a single-string compatibility snapshot if any caller inspects a default label
TOOL_STATUS_MAP: Dict[str, str] = {
    key: variants[0]
    for key, variants in TOOL_STATUS_VARIATIONS.items()
    if not key.startswith("_")
}

_BAG_LOCK = threading.Lock()
_SHUFFLE_BAGS: Dict[str, List[str]] = {}
_LAST_PICKED: Dict[str, str] = {}


def pick_tool_status_tag(tool_name: str, is_multi_tool: bool = False) -> str:
    """
    Picks one organic status phrase for `tool_name` (or multi-tool turns) using a
    per-key shuffled bag so all 10 phrases rotate naturally without back-to-back repeats.
    """
    key = "_multi_tool" if is_multi_tool else (tool_name if tool_name in TOOL_STATUS_VARIATIONS else "_default")
    variants = TOOL_STATUS_VARIATIONS.get(key) or TOOL_STATUS_VARIATIONS["_default"]
    if len(variants) == 1:
        return variants[0]

    with _BAG_LOCK:
        bag = _SHUFFLE_BAGS.get(key)
        if not bag:
            bag = list(variants)
            random.shuffle(bag)
            last = _LAST_PICKED.get(key)
            # Ensure bag boundary never repeats the exact phrase just shown
            if last and bag[-1] == last and len(bag) > 1:
                swap_idx = random.randrange(0, len(bag) - 1)
                bag[-1], bag[swap_idx] = bag[swap_idx], bag[-1]
            _SHUFFLE_BAGS[key] = bag

        chosen = bag.pop()
        _LAST_PICKED[key] = chosen
        return chosen
